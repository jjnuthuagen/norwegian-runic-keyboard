#!/usr/bin/env python3
"""Generate a runic typeface from skeletons, parametrically.

Runes are a stave plus branches, which means they can be *described*
rather than drawn: each glyph below is a list of strokes on a shared
grid, and the outlines are generated by offsetting those centrelines.
Curvature, weight and spacing are dials, so a redesign is a rebuild
rather than a redraw.

Skeletons were derived from Noto Sans Runic's own outlines (cap height
714, stroke weight 92) so the letterforms stay correct; the parameters
are then free to depart from it.

Two things matter for the result not looking broken:

* A shape that turns a corner is ONE path offset as a whole, with
  mitred joins. Offsetting each segment separately and stacking them
  leaves a notch on the outside of every corner.
* Overlapping strokes are not booleaned. TrueType fills by nonzero
  winding, so contours wound the same direction merge for free -- which
  is why this needs no boolean-operations library.
"""

