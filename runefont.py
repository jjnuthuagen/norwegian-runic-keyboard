#   S                 full-height stave at x=0
#   V x y0 y1         vertical segment
#   L x0 y0 x1 y1     straight stroke
#   C x0 y0 x1 y1 [s] bowed stroke; s=-1 bows the other way. Branches
#                     bow AWAY from the stave, or they close over the dot
